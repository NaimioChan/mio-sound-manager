// Generates crates/reslip-index/src/classify/dictionary.rs from the reference
// implementation in the Slip Sound repo.
//
// The classifier's dictionary is data, not logic: 460+ keywords across 29
// category entries, plus multi-word phrases. Transcribing it by hand would
// silently drift from the reference, so it is generated instead. The generated
// file is committed; this script only needs to run when the reference changes.
//
//   node tools/gen-category-dict.mjs [path-to-slip-sound]
//
// Default source: ../slip-sound (sibling checkout).

import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '..')
const reference = resolve(process.argv[2] ?? join(repo, '..', 'slip-sound'))
const source = join(reference, 'src', 'main', 'category-dictionary.ts')
const target = join(repo, 'crates', 'reslip-index', 'src', 'classify', 'dictionary.rs')

const mod = await import(pathToFileURL(source).href)
const dictionary = mod.CATEGORY_DICTIONARY

const rustString = (s) => JSON.stringify(s) // JSON escapes are a subset of Rust's
const rustList = (items, indent) => {
  if (!items || items.length === 0) return '&[]'
  const pad = ' '.repeat(indent)
  const lines = []
  let line = ''
  for (const item of items) {
    const piece = `${rustString(item)}, `
    if ((pad + line + piece).length > 100) {
      lines.push(pad + line.trimEnd())
      line = ''
    }
    line += piece
  }
  if (line) lines.push(pad + line.trimEnd())
  return `&[\n${lines.join('\n')}\n${' '.repeat(indent - 4)}]`
}

const entries = dictionary.map((def) => {
  const sub = def.subcategory ? `Some(${rustString(def.subcategory)})` : 'None'
  return `    CategoryDefinition {
        category: ${rustString(def.category)},
        subcategory: ${sub},
        keywords: ${rustList(def.keywords, 12)},
        phrases: ${rustList(def.phrases, 12)},
    },`
})

const header = `// Generated by tools/gen-category-dict.mjs from the Slip Sound reference
// implementation (src/main/category-dictionary.ts). Do not edit by hand: run the
// generator instead, so the two classifiers keep the same vocabulary.

use super::CategoryDefinition;

pub static CATEGORY_DICTIONARY: &[CategoryDefinition] = &[
${entries.join('\n')}
];
`

mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, header)
const keywords = dictionary.reduce((n, d) => n + d.keywords.length, 0)
const phrases = dictionary.reduce((n, d) => n + (d.phrases?.length ?? 0), 0)
console.log(`wrote ${target}`)
console.log(`entries ${dictionary.length}, keywords ${keywords}, phrases ${phrases}`)
